import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(root, 'src/content/main.js');

const TARGETS = [
  { name: 'chromium', manifest: 'src/manifest.chromium.json' },
  { name: 'firefox', manifest: 'src/manifest.firefox.json' },
];

// Content scripts cannot be ES modules, so the small module graph is inlined
// into a single IIFE. Only named imports and named exports are supported.
const importPattern = () => /^import\s+\{([^}]*)\}\s+from\s+['"]([^'"]+)['"];?\s*$/gm;
const exportPattern = () => /^export\s+(?=(?:async\s+)?function|const|let|var|class)/gm;

const modules = [];
const seen = new Set();

function collect(file) {
  if (seen.has(file)) return;
  seen.add(file);
  const source = readFileSync(file, 'utf8');
  for (const match of source.matchAll(importPattern())) {
    collect(resolve(dirname(file), match[2]));
  }
  const body = source
    .replace(importPattern(), '')
    .replace(exportPattern(), '')
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, '')
    .trim();
  modules.push({ file, body });
}

collect(entry);

// All modules share one scope after inlining, so duplicate declarations would
// silently break the bundle at runtime.
const declared = new Map();
for (const { file, body } of modules) {
  for (const match of body.matchAll(/^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    const name = match[1];
    if (declared.has(name)) {
      throw new Error(
        `duplicate top-level declaration "${name}" in ${relative(root, file)} and ${relative(root, declared.get(name))}`,
      );
    }
    declared.set(name, file);
  }
}

const bundle = [
  '/* generated by scripts/build.mjs - do not edit */',
  '(function () {',
  "'use strict';",
  '',
  modules.map(({ file, body }) => `// ${relative(root, file)}\n${body}`).join('\n\n'),
  '',
  '})();',
  '',
].join('\n');

if (/^(?:import|export)\s/m.test(bundle)) {
  throw new Error('bundle still contains module syntax');
}

for (const target of TARGETS) {
  const outDir = resolve(root, 'dist', target.name);
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, 'content.js'), bundle);
  writeFileSync(resolve(outDir, 'manifest.json'), readFileSync(resolve(root, target.manifest), 'utf8'));
  console.log(`${target.name}: dist/${target.name}/ {manifest.json, content.js}`);
}
